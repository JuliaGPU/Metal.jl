# generate src/metallib/airr_schema.jl, the schema of the reflection data in Metal libraries
#
# Usage: julia res/airr/generate.jl [AIR_OBJDUMP]
#
# The schema is embedded in binary form (BFBS) in Apple's `air-objdump`, which decodes the
# reflection data for `metal-objdump --reflection`. Pass its path, or have it found in the
# directory METAL_TOOLCHAIN names or with `xcrun`.

module FlatBuffers
include(joinpath(@__DIR__, "..", "..", "src", "metallib", "flatbuffers.jl"))
end
using .FlatBuffers: read_bfbs, FBSchema, FBObject, FBEnum, FBField, FBType

using SHA: sha256

function find_objdump()
    if haskey(ENV, "METAL_TOOLCHAIN")
        return joinpath(ENV["METAL_TOOLCHAIN"], "air-objdump")
    end
    return strip(read(`xcrun --find air-objdump`, String))
end

# the AIRR schema in a binary: the BFBS buffer whose file identifier is AIRR. (binaries can
# embed the same schema several times; we check that they agree)
function find_schema(binary::Vector{UInt8})
    found = nothing
    for range in findall(codeunits("BFBS"), binary)
        start = first(range) - 5    # (the identifier follows the root offset)
        schema = try
            read_bfbs(binary[start+1:end])
        catch
            continue
        end
        schema.file_identifier == "AIRR" || continue
        if found === nothing
            found = (; schema, offset = start)
        elseif sprint(write_schema, schema) != sprint(write_schema, found.schema)
            error("found different AIRR schemas, at offsets $(found.offset) and $start")
        end
    end
    found === nothing && error("found no AIRR schema")
    return found
end

lit(x) = repr(x)
lit(t::FBType) = "FBType($(t.base), $(t.element), $(t.index), $(Int(t.fixed_length)))"

function write_schema(io::IO, schema::FBSchema)
    println(io, "const airr_schema = FBSchema(")
    println(io, "    $(lit(schema.file_identifier)), $(schema.root_table),")
    println(io, "    FBObject[")
    for (i, obj) in enumerate(schema.objects)
        println(io, "        # $(i-1)")
        println(io, "        FBObject($(lit(obj.name)), $(obj.is_struct), $(obj.bytesize), FBField[")
        for f in obj.fields
            println(io, "            FBField($(lit(f.name)), $(lit(f.type)), $(Int(f.id)), ",
                    "$(Int(f.offset)), $(f.default_integer), $(f.default_real), $(f.deprecated)),")
        end
        println(io, "        ]),")
    end
    println(io, "    ],")
    println(io, "    FBEnum[")
    for (i, enum) in enumerate(schema.enums)
        println(io, "        # $(i-1)")
        println(io, "        FBEnum($(lit(enum.name)), $(enum.is_union), $(enum.underlying), [")
        for (name, value) in enum.values
            println(io, "            $(lit(name)) => $value,")
        end
        print(io, "        ], Int32[")
        enum.is_union && print(io, join(enum.union_objects, ", "))
        println(io, "]),")
    end
    println(io, "    ])")
end

function main(args)
    objdump = isempty(args) ? find_objdump() : args[1]
    binary = read(objdump)
    (; schema, offset) = find_schema(binary)
    version = let metal = joinpath(dirname(objdump), "metal")
        isfile(metal) ? first(eachline(`$metal --version`)) : "unknown"
    end

    output = joinpath(@__DIR__, "..", "..", "src", "metallib", "airr_schema.jl")
    open(output, "w") do io
        println(io, """
            # the schema of the AIRR reflection data in Metal libraries
            #
            # generated by res/airr/generate.jl, do not edit. extracted from:
            # - binary: $(basename(objdump)), sha256 $(bytes2hex(sha256(binary)))
            # - offset: $(offset)
            # - toolchain: $version
            """)
        write_schema(io, schema)
    end
    println("wrote $(length(schema.objects)) objects and $(length(schema.enums)) enums to ",
            normpath(output))
end

isinteractive() || main(ARGS)
